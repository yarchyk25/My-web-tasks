// сума / кількість
$average = array_sum($arr_numbers) / count($arr_numbers);

echo "Середнє арифметичне: $average <br>";

// Студенти і бали
$students = [
    "Іваненко І.І." => 95,
    "Петренко П.П." => 75,
    "Сидоренко С.С." => 88
];

echo "Студенти-відмінники: ";

// Вивід тих, у кого > 80
foreach ($students as $student => $score) {
    if ($score > 80) {
        echo "$student ($score); ";
    }
}

echo "<br>";

// Перевірка кратності
$num = 12;

// || — логічне "або"
if ($num % 3 == 0 || $num % 5 == 0) {
    echo "Число $num кратне 3 або 5.<br>";
}

// Таблиця множення
echo "Таблиця множення на 7:<br>";

// for — цикл з лічильником
for ($i = 1; $i <= 10; $i++) {
    echo "7 * $i = " . (7 * $i) . " | ";
}

echo "<hr>";



