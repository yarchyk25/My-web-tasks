<?php

// ВАРІАНТ 1 

echo "<h2>Варіант 1</h2>";

// Оголошення змінних різних типів
$name = "Олексій"; // рядок (string)
$age = 20;         // ціле число (integer)
$is_student = true; // логічне значення (boolean)

// Тернарний оператор (скорочений if)
// якщо $is_student = true → "є студентом", інакше → "не є студентом"
$student_status = $is_student ? "є студентом" : "не є студентом";

// Вивід тексту з підстановкою змінних
echo "Мене звати $name, мені $age років, і я $student_status.<br>";

// Створення масиву чисел
$numbers = [1, 2, 3, 4, 5];

// array_sum() — рахує суму всіх елементів масиву
$sum = array_sum($numbers);

echo "Сума елементів масиву [1,2,3,4,5]: $sum <br>";

// Асоціативний масив (ключ => значення)
$contact = [
    "name" => "Олексій",
    "email" => "alex@example.com",
    "phone" => "+380000000000"
];

// Початок HTML списку
echo "<ul>";

// foreach перебирає масив:
// $key — ключ (name, email)
// $value — значення
foreach ($contact as $key => $value) {
    echo "<li><b>$key:</b> $value</li>";
}

// Кінець списку
echo "</ul>";

// Умова: якщо вік більше 18
if ($age > 18) {
    echo "Вік більше 18 років.<br>";
}

// Перевірка оцінки
$grade = 85;

// && означає "і"
if ($grade >= 90 && $grade <= 100) {
    echo "Оцінка: Відмінно";
} elseif ($grade >= 70) {
    echo "Оцінка: Добре";
} elseif ($grade >= 50) {
    echo "Оцінка: Задовільно";
} else {
    echo "Оцінка: Незадовільно";
}

echo "<hr>"; // горизонтальна лінія



//  ВАРІАНТ 2 

echo "<h2>Варіант 2</h2>";

// Дві змінні
$a = 5;
$b = 10;

// Арифметичні операції
echo "Сума: " . ($a + $b) . "<br>";       // додавання
echo "Різниця: " . ($a - $b) . "<br>";    // віднімання
echo "Добуток: " . ($a * $b) . "<br>";    // множення
echo "Ділення: " . ($a / $b) . "<br>";    // ділення

// Масив днів тижня (індекси починаються з 0)
$days = ["Понеділок", "Вівторок", "Середа", "Четвер", "П'ятниця", "Субота", "Неділя"];

// Вивід елементів по індексу
echo "3-й день: " . $days[2] . "<br>"; 
echo "5-й день: " . $days[4] . "<br>";

// Асоціативний масив товарів
$products = ["Хліб" => 25, "Молоко" => 35, "Сир" => 120];

// Перебір товарів
foreach ($products as $product => $price) {
    echo "Товар: $product, Ціна: $price грн<br>";
}

// switch — перевірка значення змінної
$current_day = "Monday";

switch ($current_day) {
    case "Monday":
        echo "Сьогодні понеділок - важкий день.<br>";
        break; // вихід зі switch

    case "Friday":
        echo "Сьогодні п'ятниця - скоро вихідні!<br>";
        break;

    default:
        echo "Звичайний робочий день.<br>";
}

// Перевірка на парність
$x = 15;

// % — остача від ділення
if ($x % 2 == 0) {
    echo "Число $x - парне.";
} else {
    echo "Число $x - непарне.";
}

echo "<hr>";



// ВАРІАНТ 3 

echo "<h2>Варіант 3</h2>";

// Ціни товарів
$item1 = 150;
$item2 = 200;
$item3 = 250;

// Загальна сума
$total_price = $item1 + $item2 + $item3;

// Масив фільмів
$movies = ["Початок", "Матриця", "Інтерстеллар", "Дюна", "Тенет"];

echo "Улюблені фільми: ";

// Перебір масиву
foreach ($movies as $movie) {
    echo "$movie; ";
}

echo "<br>";

// Дані користувача
$user = [
    "login" => "admin",
    "password" => "12345",
    "email" => "admin@web.com"
];

// Вивід даних
echo "Користувач: " . $user['login'] . " (Email: " . $user['email'] . ")<br>";

// Якщо сума більше 500 — даємо знижку
if ($total_price > 500) {
    $discount = $total_price * 0.1; // 10%
    $total_price -= $discount;      // віднімаємо
    echo "Надано знижку 10%. До сплати: $total_price грн<br>";
}

// Введені дані
$input_login = "admin";
$input_pass = "12345";

// === — строге порівняння (тип і значення)
// && — логічне "і"
if ($input_login === $user['login'] && $input_pass === $user['password']) {
    echo "Доступ дозволено!";
} else {
    echo "Помилка авторизації!";
}

echo "<hr>";



//  ВАРІАНТ 4 

echo "<h2>Варіант 4</h2>";

$n1 = 45;
